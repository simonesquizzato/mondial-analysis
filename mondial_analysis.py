lr2.rvalue

"""#FOCUS 3:

##Individuiamo la religione predominante per i paesi che presentano una delle cinque forme di governo piú diffuse.
"""

data_gov_rel = data.groupby(['Government', 'Religion']).size().reset_index(name='Count')

max_indices = data_gov_rel.groupby('Government')['Count'].idxmax()

rel_per_gov = {}

for idx in max_indices:
    row = data_gov_rel.loc[idx]
    government = row['Government']
    religion = row['Religion']
    rel_per_gov[government] = religion

top5_gov = data["Government"].value_counts().head(5)

rel_top5_gov = {}

for gov, rel in rel_per_gov.items():
  if gov in top5_gov:
    rel_top5_gov[gov] = rel

rel_top5_gov

"""##Selezionamo i paesi che presentano una delle coppie governo-religione appena individuate. Studiamo il GDP di tali paesi in confronto al GDP dei restanti."""

nation_sel = []

for index, row in data.iterrows():
    governo = row["Government"]
    religione = row["Religion"]
    if (governo, religione) in rel_top5_gov.items():
        nation_sel.append(row["Nation"])

data[data['Nation'].isin(nation_sel)].groupby("Continent")["GDP"].describe()

data[~data['Nation'].isin(nation_sel)].groupby("Continent")["GDP"].describe()

"""#FOCUS 4:

##Verifichiamo l'eventuale corrispondenza della religione dei paesi non indipendenti con la religione dei rispettivi paesi da cui dipendono.
"""

dep_nat = data[data['Dependent'].notna()]

indep_nat = data[data['Dependent'].isna()]

rel_df = dep_nat.merge(indep_nat, left_on = 'Dependent', right_on = 'Code')

rel_df = rel_df[['Nation_x', 'Dependent_x', 'Religion_x', 'Religion_y']]

rel_df.rename(columns={'Nation_x': 'Nation', 'Dependent_x': 'Dependent', 'Religion_x': 'Religion_Dependent', 'Religion_y': 'Religion_Independent'}, inplace=True)

rel_df['Match'] = rel_df['Religion_Dependent'] == rel_df['Religion_Independent']

