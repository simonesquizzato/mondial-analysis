from sqlalchemy import create_engine
from sqlalchemy import text
import pandas as pd
import scipy.stats as stats
import numpy as np
import seaborn as sns
from sklearn.naive_bayes import GaussianNB
from sklearn.metrics import accuracy_score
from sklearn.model_selection import train_test_split

engine = create_engine("mysql+mysqlconnector://guest:relational@db.relational-data.org/Mondial", echo=False)

c = engine.connect()

q = """SELECT encompasses.Continent, country.Name AS Nation, country.Code,
       country.Population, politics.Government, politics.Dependent, economy.GDP, population.Infant_Mortality,
       population.Population_Growth, religion.Name AS Religion
FROM country
JOIN encompasses ON country.Code = encompasses.Country
JOIN economy ON country.Code = economy.Country
JOIN population ON country.Code = population.Country
JOIN politics ON country.Code = politics.Country
JOIN religion ON country.Code = religion.Country
WHERE religion.Percentage = (
    SELECT MAX(r2.Percentage)
    FROM religion AS r2
    WHERE r2.Country = country.Code
) AND encompasses.Percentage = (
    SELECT MAX(e2.Percentage)
    FROM encompasses AS e2
    WHERE e2.Country = country.Code)
"""

data = pd.read_sql_query(text(q), c)

"""#EDA"""

data.head()

data.describe()

"""##Analizziamo la distribuzione delle variabili quantitative in relazione alla variabile Continent."""

data["log_GDP"] = np.log(data["GDP"])
data["log_Population"] = np.log(data["Population"])

sns.pairplot(data=data, vars=["Population_Growth", "Infant_Mortality", "log_Population", "log_GDP"], hue="Continent")

"""#FOCUS 1:

##Analizziamo la relazione tra le variabili Infant_Mortality e Population_Growth.
"""

data1 = data.dropna(subset=['Infant_Mortality', 'Population_Growth'])

q95_pop_growth = data1['Population_Growth'].quantile(0.95)
q95_inf_mort = data1['Infant_Mortality'].quantile(0.95)

data_q95 = data1[(data1['Population_Growth'] <= q95_pop_growth) &
                      (data1['Infant_Mortality'] <= q95_inf_mort)]

sns.lmplot(x = "Population_Growth", y = "Infant_Mortality", data = data_q95, fit_reg = True)

lr1 = stats.linregress(data_q95["Population_Growth"], data_q95["Infant_Mortality"])

lr1.rvalue

"""##Costruiamo un classificatore per la variabile Continent basandoci sulle variabili Population_Growth e Infant_Mortality."""

classifier = GaussianNB()

X = data1[['Infant_Mortality', 'Population_Growth']]
Y = data1["Continent"]
data1_cl = pd.concat([X, Y], axis = 1)

x_train, x_test, y_train, y_test = train_test_split(data1_cl[data1_cl.columns[:2]], data1_cl["Continent"], test_size = 0.2, random_state=99)

classifier.fit(X=x_train, y=y_train)

pred = classifier.predict(x_test)

accuracy_score(y_test, pred)

"""#FOCUS 2:

##Analizziamo la relazione tra le variabili Population e GDP.
"""

data2 = data.dropna(subset=['GDP', 'Population'])

data2["log_Population"] = np.log(data2["Population"])
data2["log_GDP"] = np.log(data2["GDP"])

sns.lmplot(x = "log_Population", y = "log_GDP", data = data2, fit_reg = True)

